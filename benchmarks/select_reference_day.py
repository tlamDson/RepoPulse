"""Pick the benchmark reference day from GH Archive and write ``benchmarks/reference.toml``.

Usage::

    python benchmarks/select_reference_day.py 2026-10-25 2026-10-24 \
        --write benchmarks/reference.toml

Each candidate day is downloaded to ``<data-dir>/<day>/`` (gitignored), every hour is scanned
for PushEvent, and the first day that passes ``evaluate_day`` is written out with the sha256
and size of every file. Nothing in ``reference.toml`` is typed by hand.
"""

from __future__ import annotations

import argparse
import gzip
import json
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from benchmarks.download import download  # noqa: E402
from benchmarks.reference import HOURS, evaluate_day, hour_file_name, sha256_of  # noqa: E402

DEFAULT_MAX_SIZE_RATIO = 2.0
CRITERIA_TEXT = (
    "All 24 hourly files exist; every hour contains at least one PushEvent (recent GH Archive "
    "hours that lost PushEvent/CreateEvent/DeleteEvent are rejected); every hour's compressed "
    "size is within max_size_ratio of the day's median hour size (either direction)."
)


def count_push_events(path: Path) -> int:
    pushes = 0
    with gzip.open(path, "rt", encoding="utf-8") as fh:
        for line in fh:
            if json.loads(line).get("type") == "PushEvent":
                pushes += 1
    return pushes


def scan_day(day: str, data_dir: Path) -> dict[int, dict]:
    hours: dict[int, dict] = {}
    for h in HOURS:
        name = hour_file_name(day, h)
        path = data_dir / day / name
        if not path.is_file() and download(name, data_dir / day) is None:
            continue
        hours[h] = {
            "name": name,
            "bytes": path.stat().st_size,
            "push_events": count_push_events(path),
            "sha256": sha256_of(path),
        }
    return hours


def render_toml(day: str, hours: dict[int, dict], max_size_ratio: float) -> str:
    lines = [
        "# Benchmark reference day (real GH Archive data). Generated by",
        "# benchmarks/select_reference_day.py; do not edit by hand.",
        f'data_date = "{day}"',
        'url_template = "https://data.gharchive.org/{name}"',
        "",
        "[criteria]",
        f'description = "{CRITERIA_TEXT}"',
        "hours_required = 24",
        "push_event_every_hour = true",
        f"max_size_ratio = {max_size_ratio}",
    ]
    for h in HOURS:
        stats = hours[h]
        lines += [
            "",
            "[[files]]",
            f"hour = {h}",
            f'name = "{stats["name"]}"',
            f'sha256 = "{stats["sha256"]}"',
            f"bytes = {stats['bytes']}",
            f"push_events = {stats['push_events']}",
        ]
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("days", nargs="+", help="candidate days, tried in order (YYYY-MM-DD)")
    parser.add_argument("--data-dir", type=Path, default=Path("data/raw/gharchive"))
    parser.add_argument("--max-size-ratio", type=float, default=DEFAULT_MAX_SIZE_RATIO)
    parser.add_argument("--write", type=Path, help="write reference.toml for the first good day")
    args = parser.parse_args(argv)

    for day in args.days:
        hours = scan_day(day, args.data_dir)
        problems = evaluate_day(hours, max_size_ratio=args.max_size_ratio)
        for h in sorted(hours):
            s = hours[h]
            print(f"{day} h{h:02d} bytes={s['bytes']} push={s['push_events']} {s['sha256']}")
        if problems:
            print(f"{day}: rejected")
            for p in problems:
                print(f"  - {p}")
            continue
        print(f"{day}: accepted")
        if args.write:
            args.write.write_text(render_toml(day, hours, args.max_size_ratio), encoding="utf-8")
            print(f"wrote {args.write}")
        return 0
    print("no candidate day passed", file=sys.stderr)
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
